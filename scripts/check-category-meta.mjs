#!/usr/bin/env node

/**
 * check-category-meta.mjs — guard against silently-dropped category metadata.
 *
 * CANONICAL COPY: wisdom-tweaker/shared/scripts/. Distributed verbatim to every
 * *-wisdom repo as scripts/check-category-meta.mjs. Edit it here, then re-sync.
 *
 * Why this exists (Takazudo/zudo-css-wisdom#183):
 *
 *   zudo-doc's `loadCategoryMeta` reads `_category_.json` with `node:fs`. Under
 *   zfb — zudo-doc's own host — the SSG bundle is built `--platform=neutral
 *   --external:node:*`, and zfb's embedded-V8 host resolves `node:fs` to a
 *   throwing proxy. `scanDir` swallows the throw in a bare `catch { return; }`
 *   and caches the resulting EMPTY map for the process lifetime.
 *
 *   Every `label`, `position`, `description` and `noPage` in every sidecar is
 *   therefore discarded — with no error, no warning, and a green build. In
 *   css-wisdom that silently published 36 category pages marked `noPage: true`,
 *   ~14% of the sitemap, and nobody noticed for months.
 *
 * Neither `zfb check`, `html-validate`, nor `check-links --strict-broken` can
 * see this: nothing is a broken link, the pages render fine — they simply
 * should not exist. Hence a dedicated source-level check.
 *
 * Checks:
 *   1. FAIL on any `_category_.json` under src/. Upstream retired the sidecar in
 *      favour of index.mdx frontmatter; any remaining file is dead weight that
 *      reads as configuration but is silently ignored.
 *   2. FAIL when a `headerNav` entry targets a page with `category_no_page:
 *      true`, in the default locale OR in any configured locale. Suppressing a
 *      category the header links to turns that link into a site-wide 404, and
 *      zfb's `--strict-broken` does NOT catch it.
 *
 * ── A NOTE ON SELF-DEFEAT ─────────────────────────────────────────────────
 * The first version of this script printed a green OK on a repo where it had
 * parsed ZERO nav entries, because that repo declares `headerNav` in
 * src/config/settings.ts and spreads it into zfb.config.ts — so the regex found
 * nothing and "checked everything successfully" was indistinguishable from
 * "checked nothing". A guard against silent false-greens that itself
 * false-greens is worse than no guard, because it manufactures confidence.
 *
 * Two rules follow, and both must be preserved by anyone editing this file:
 *   - ALWAYS report the counts actually inspected (sidecars scanned, nav entries
 *     parsed, locales considered). A reader must be able to see "0 checked".
 *   - Treat "found no headerNav at all" as a WARNING worth printing loudly, not
 *     as success. Absence of findings is not evidence of correctness.
 *
 * Unresolvable nav paths are warnings, not failures — the path→file resolution
 * is a heuristic and must not fail a build on its own uncertainty.
 *
 * ── BUILD-GENERATED NAV TARGETS ───────────────────────────────────────────
 * Some nav targets legitimately have no source file in a fresh clone because
 * the directory is produced at build time (`src/content/docs/claude/`, written
 * by the claude-resources integration, is the fleet-wide case). Warning on
 * those trains readers to ignore this guard, so an unresolved target whose
 * DIRECTORY is declared build-generated by an in-repo `.gitignore` is demoted
 * to a visible `[GENERATED]` note instead — see probeGeneratedDirs below for
 * why every part of that probe is as narrow as it is.
 *
 * The exemption is earned by a positive signal and by nothing else: any probe
 * failure, ambiguity, unrecognized ignore source, or rule merely INHERITED from
 * an ignored ancestor keeps the warning verbatim — and a probe that could not
 * run at all says so loudly rather than reporting zero exemptions.
 *
 * Usage: node scripts/check-category-meta.mjs
 * Exit:  0 = OK (warnings allowed), 1 = violations found
 * Tests: wisdom-tweaker/shared/scripts/__tests__/check-category-meta.test.mjs
 */

import { spawnSync } from "node:child_process";
import { readFile, readdir, access, realpath } from "node:fs/promises";
import { basename, isAbsolute, join, posix, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

// fileURLToPath, not .pathname — the latter keeps percent-escapes, so a checkout
// under a path with spaces or non-ASCII silently resolves to a directory that
// does not exist, walk() swallows the ENOENT, and the script exits 0 having
// scanned nothing.
const ROOT = fileURLToPath(new URL("..", import.meta.url)).replace(/[/\\]$/, "");
const SRC = join(ROOT, "src");
const CONFIG = join(ROOT, "zfb.config.ts");
// headerNav may live directly in zfb.config.ts or in a settings module that the
// config spreads. Both shapes exist across the wisdom repos.
const CONFIG_SOURCES = [CONFIG, join(ROOT, "src", "config", "settings.ts")];

const SKIP_DIRS = new Set(["node_modules", ".git", "dist", ".astro", ".zfb", ".zfb-build"]);
const PAGE_EXTS = [".mdx", ".md"];

async function exists(p) {
  try {
    await access(p);
    return true;
  } catch {
    return false;
  }
}

async function walk(dir, out = []) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    if (e.isDirectory()) {
      if (SKIP_DIRS.has(e.name)) continue;
      await walk(join(dir, e.name), out);
    } else {
      out.push(join(dir, e.name));
    }
  }
  return out;
}

/** Extract the leading `---` frontmatter block, or "" when absent. */
function frontmatter(source) {
  const m = source.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  return m ? m[1] : "";
}

/**
 * Truthiness for `category_no_page`, matching what the frontmatter parser
 * ACTUALLY produces — gray-matter/js-yaml on the YAML 1.2 core schema.
 *
 * Only `true` / `True` / `TRUE` become a boolean there. `yes` and `on` are
 * YAML 1.1 spellings that the 1.2 core schema parses as the STRINGS "yes" and
 * "on"; zudo-doc requires a boolean, so such a page is still emitted.
 *
 * Accepting them here was an overcorrection on my part and a false POSITIVE:
 * the page publishes normally, but this check would report NAV-404 and fail
 * CI. A guard that blocks correct code is worse than the gap it closed — so
 * the accepted set is exactly the three spellings that really suppress a page.
 * Measured against js-yaml in zudo-test-wisdom, not inferred from the spec.
 *
 * Still tolerates a trailing `# comment`, which the original form missed.
 */
function hasNoPage(fm) {
  const m = fm.match(/^\s*category_no_page\s*:\s*([^#\r\n]*)/m);
  if (!m) return false;
  return /^true$/i.test(m[1].trim());
}

/**
 * Pull `path:` values out of a `headerNav: [ ... ]` array. Regex rather than a
 * TS parse: the configs are plain literals and this script stays dependency-free.
 * Returns [] when the file declares no headerNav.
 */
function parseHeaderNav(source) {
  const start = source.indexOf("headerNav:");
  if (start === -1) return [];
  const open = source.indexOf("[", start);
  if (open === -1) return [];
  let depth = 0;
  let end = -1;
  for (let i = open; i < source.length; i++) {
    if (source[i] === "[") depth++;
    else if (source[i] === "]") {
      depth--;
      if (depth === 0) {
        end = i;
        break;
      }
    }
  }
  if (end === -1) return [];
  return [...source.slice(open, end).matchAll(/path\s*:\s*["'`]([^"'`]+)["'`]/g)].map((m) => m[1]);
}

function parseDocsDir(source) {
  const m = source.match(/docsDir\s*:\s*["']([^"']+)["']/);
  return m ? m[1] : "src/content/docs";
}

function parseBase(source) {
  const m = source.match(/\bbase\s*:\s*["']([^"']*)["']/);
  return m ? m[1] : "/";
}

/**
 * Parse `locales: { ja: { label: "JA", dir: "src/content/docs-ja" }, ... }`.
 * A locale-only `category_no_page` suppresses that locale's route while the
 * localized header link survives — the headline failure mode, and one the
 * default-docsDir-only resolution was completely blind to.
 */
function parseLocales(source) {
  const start = source.indexOf("locales:");
  if (start === -1) return [];
  const open = source.indexOf("{", start);
  if (open === -1) return [];
  let depth = 0;
  let end = -1;
  for (let i = open; i < source.length; i++) {
    if (source[i] === "{") depth++;
    else if (source[i] === "}") {
      depth--;
      if (depth === 0) {
        end = i;
        break;
      }
    }
  }
  if (end === -1) return [];
  const block = source.slice(open, end);
  // Key may be bare (`ja:`) or quoted, and BCP-47 tags contain hyphens
  // (`"pt-BR"`, `zh-Hant`). A bare-\w+ pattern skipped those locales entirely,
  // so a localized index with category_no_page would never be inspected and CI
  // would pass on a 404ing localized nav route — the same false-green class as
  // the bugs above.
  return [
    ...block.matchAll(/["']?([\w-]+)["']?\s*:\s*\{[^}]*?\bdir\s*:\s*["']([^"']+)["']/g),
  ].map((m) => ({ locale: m[1], dir: m[2] }));
}

/**
 * ── The build-generated-directory probe ───────────────────────────────────
 *
 * Asks git whether an unresolved nav target's DIRECTORY is ignored, and accepts
 * that as "the repo says this is build-generated" only when the matching rule
 * came from a `.gitignore` inside the repo. Every restriction below closes a
 * specific way this could exempt a genuinely broken nav link:
 *
 *   - Probe the directory, never the synthetic `index.mdx`. A repo with a broad
 *     `*.mdx` rule matches the file but NOT the directory, so the file-level
 *     probe would exempt every unresolvable nav entry in that repo. (Verified:
 *     `*.mdx` returns exit 1 for `src/content/docs/claude/`.)
 *   - Probe WITH a trailing slash. Directory-only rules (`src/content/docs/
 *     claude/`, which is the form all six wisdom repos use) do not match the
 *     same path without one — git returns exit 1 and the exemption silently
 *     never fires.
 *   - `-v -z` and inspect the matching source. `-q` hides which file matched,
 *     so a developer's `.git/info/exclude` or `core.excludesFile` — local
 *     machine state, not evidence committed to the repo — could silence this
 *     check for everyone. Both are rejected here: the first fails the
 *     `.gitignore` basename test, the second falls outside the repo root.
 *   - `-z` output is NUL-delimited 4-tuples. Never split verbose output on
 *     `:` — Windows drive letters and the pattern text both contain colons.
 *   - Require git's top level to equal realpath(ROOT). A checkout merely nested
 *     inside an unrelated repo would otherwise be answered by that outer repo's
 *     ignore rules.
 *   - Sanitize GIT_DIR / GIT_WORK_TREE / GIT_INDEX_FILE, or `cwd` does not
 *     reliably select which repository answers.
 *   - No `--no-index`. The generated path is already untracked, and that flag
 *     also applies ignore rules to tracked paths, which weakens behaviour on
 *     sparse checkouts and deleted tracked files.
 *   - Spawn without a shell and batch every path through `--stdin`, one call.
 *     Measured gotcha: with `--stdin`, only MATCHING paths appear in the
 *     output, so results must be correlated by the path field — never by line
 *     order against the input list.
 *   - Probe each target's PARENT too, and refuse the exemption when the parent
 *     is ignored as well. gitignore rules are inherited downward, so a single
 *     broad ancestor rule (`docs/`, `content/`, a wholesale-ignored content
 *     dir) matches every target beneath it — including a genuinely mistyped nav
 *     path — and would silently turn this whole guard off while still printing
 *     a plausible `[GENERATED]` note citing a real rule. A rule scoped to the
 *     generated directory itself leaves the parent unignored; an inherited one
 *     does not. (Verified: with `docs/` ignored, git reports
 *     `src/content/docs/typo-nowhere/` AND `src/content/docs/` as ignored.)
 *
 * Exit codes: 0 plus an accepted source is the only path to an exemption. 1
 * (nothing ignored), 128 (not a work tree, bare repo, git absent) and every
 * other outcome keep the warning. A failed probe must make this guard more
 * conservative, never less — AND must say so: reporting "probed N dirs" when
 * git was never consulted is the same manufactured confidence this file's
 * self-defeat note forbids.
 */
const GIT_ENV_TO_CLEAR = ["GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE"];

function runGit(args, input) {
  const env = { ...process.env };
  for (const k of GIT_ENV_TO_CLEAR) delete env[k];
  return spawnSync("git", args, {
    cwd: ROOT,
    env,
    input,
    encoding: "utf-8",
    shell: false,
    windowsHide: true,
    maxBuffer: 16 * 1024 * 1024,
  });
}

async function gitTopLevelIsRoot() {
  const r = runGit(["rev-parse", "--show-toplevel"]);
  if (r.error || r.status !== 0) return false;
  const top = r.stdout.trim();
  if (!top) return false;
  try {
    // realpath both sides: /tmp is a symlink to /private/tmp on macOS, and git
    // reports the physical path — a raw string compare fails there.
    return (await realpath(top)) === (await realpath(ROOT));
  } catch {
    return false;
  }
}

/** True only for a `.gitignore` file physically inside the repository. */
function isRepoGitignoreSource(source, realRoot) {
  if (!source) return false;
  if (source.startsWith("<")) return false; // git's `<command line>` pseudo-source
  const abs = resolve(realRoot, source);
  if (basename(abs) !== ".gitignore") return false; // rejects .git/info/exclude
  const rel = relative(realRoot, abs);
  if (!rel || rel.startsWith("..") || isAbsolute(rel)) return false; // rejects core.excludesFile
  return !rel.split(/[/\\]/).includes(".git");
}

/** Repo-relative, POSIX, trailing-slash dir for a nav slug — or null if it escapes ROOT. */
function targetDirFor(dir, slug) {
  const norm = posix.normalize((slug ? `${dir}/${slug}` : dir).replace(/\\/g, "/"));
  if (norm.startsWith("/") || norm === "." || norm === ".." || norm.startsWith("../")) return null;
  return `${norm.replace(/\/+$/, "")}/`;
}

/** Immediate parent of a trailing-slash repo-relative dir, or null at the top. */
function parentDirOf(dir) {
  const parent = posix.dirname(dir.replace(/\/+$/, ""));
  if (!parent || parent === "." || parent === "/" || parent === "..") return null;
  return `${parent}/`;
}

/**
 * Probe result: `{ ran, reason, accepted }`. `accepted` maps probed dir →
 * "source:line" for the dirs an in-repo .gitignore covers by a rule scoped to
 * that dir. `ran` is false whenever git could not be consulted at all, so the
 * caller never reports a probe that did not happen.
 */
async function probeGeneratedDirs(dirs) {
  const accepted = new Map();
  const skipped = (reason) => ({ ran: false, reason, accepted });
  if (dirs.length === 0) return { ran: true, reason: null, accepted };
  if (!(await gitTopLevelIsRoot())) {
    return skipped("git could not answer for this checkout (not a work tree, or its top level is not the repo root)");
  }

  let realRoot;
  try {
    realRoot = await realpath(ROOT);
  } catch {
    return skipped("the repo root could not be resolved");
  }

  // Parents ride along in the same batch so the ancestor test costs no extra spawn.
  const parents = new Map(dirs.map((d) => [d, parentDirOf(d)]));
  const probe = [...new Set([...dirs, ...[...parents.values()].filter(Boolean)])];

  const r = runGit(["check-ignore", "-z", "-v", "--stdin"], probe.map((d) => `${d}\0`).join(""));
  if (r.error) return skipped(`git could not be run (${r.error.message})`);
  // 0 = something matched, 1 = nothing matched. Anything else (128: bare repo,
  // git absent) means the answer is unknown, not "not generated".
  if (r.status !== 0 && r.status !== 1) {
    return skipped(`git check-ignore exited ${r.status}`);
  }

  const ignoredAny = new Set();
  const scoped = new Map();
  const fields = r.stdout.split("\0"); // <source> <linenum> <pattern> <pathname>, repeating
  for (let i = 0; i + 3 < fields.length; i += 4) {
    const source = fields[i];
    const line = fields[i + 1];
    const pathname = fields[i + 3];
    if (!pathname) continue;
    ignoredAny.add(pathname);
    if (!isRepoGitignoreSource(source, realRoot)) continue;
    scoped.set(pathname, `${source}:${line}`);
  }

  for (const dir of dirs) {
    const rule = scoped.get(dir);
    if (!rule) continue;
    const parent = parents.get(dir);
    // An ignored parent means the rule is inherited, not scoped to this dir —
    // it is evidence about the whole subtree, so it is no evidence at all here.
    if (parent && ignoredAny.has(parent)) continue;
    accepted.set(dir, rule);
  }
  return { ran: true, reason: null, accepted };
}

const failures = [];
const warnings = [];
const notes = [];

// ── Check 1: no _category_.json sidecars ──────────────────────────────────
const srcFiles = await walk(SRC);
// sep-aware so this also matches on Windows backslash paths.
const sidecars = srcFiles.filter(
  (f) => f.endsWith(`${sep}_category_.json`) || f.endsWith("/_category_.json"),
);

if (srcFiles.length === 0) {
  warnings.push(
    `[EMPTY-SCAN] no files found under ${relative(ROOT, SRC)}/ — the sidecar ` +
      `check inspected nothing. Verify the repo layout; this is not a pass.`,
  );
}
notes.push(`scanned ${srcFiles.length} source file(s) under ${relative(ROOT, SRC)}/`);

for (const f of sidecars) {
  failures.push(
    `[SIDECAR] ${relative(ROOT, f)} — _category_.json is silently ignored by ` +
      `zudo-doc under zfb. Move label/position/description/noPage into the ` +
      `directory's index.mdx frontmatter (sidebar_label / sidebar_position / ` +
      `description / category_no_page) and delete this file.`,
  );
}

// ── Check 2: headerNav must not target a suppressed category ──────────────
let navPaths = [];
let navSource = null;
let docsDir = "src/content/docs";
let base = "/";
let locales = [];

for (const candidate of CONFIG_SOURCES) {
  if (!(await exists(candidate))) continue;
  const source = await readFile(candidate, "utf-8");
  if (docsDir === "src/content/docs") docsDir = parseDocsDir(source);
  if (base === "/") base = parseBase(source);
  if (locales.length === 0) locales = parseLocales(source);
  const found = parseHeaderNav(source);
  if (found.length > 0 && navPaths.length === 0) {
    navPaths = found;
    navSource = candidate;
  }
}

if (navPaths.length === 0) {
  warnings.push(
    `[NO-NAV] no headerNav entries found in ${CONFIG_SOURCES.map((c) => relative(ROOT, c)).join(" or ")}. ` +
      `The headerNav→suppressed-category check inspected ZERO links. If this ` +
      `site does define a header nav, it is declared somewhere this script does ` +
      `not look and the check is a no-op — fix the canonical script in ` +
      `wisdom-tweaker/shared/scripts/ rather than ignoring this warning.`,
  );
} else {
  notes.push(
    `parsed ${navPaths.length} headerNav entr(ies) from ${relative(ROOT, navSource)}`,
  );
}
notes.push(
  locales.length > 0
    ? `checking ${locales.length + 1} locale dir(s): ${docsDir}, ${locales.map((l) => l.dir).join(", ")}`
    : `checking 1 locale dir: ${docsDir}`,
);

/** Candidate source files for a nav slug within one content dir. */
function candidatesFor(dir, slug) {
  const out = [];
  for (const ext of PAGE_EXTS) {
    if (slug) {
      out.push(join(ROOT, dir, slug, `index${ext}`));
      out.push(join(ROOT, dir, `${slug}${ext}`));
    } else {
      out.push(join(ROOT, dir, `index${ext}`));
    }
  }
  return out;
}

// Unresolved entries are collected, not warned on immediately: they are
// resolved against .gitignore in ONE batched git call after the loop.
const unresolved = [];

for (const navPath of navPaths) {
  let slug = navPath;
  if (base && base !== "/" && slug.startsWith(base)) slug = slug.slice(base.length);
  slug = slug.replace(/^\/+/, "").replace(/\/+$/, "");
  if (slug === "docs") slug = "";
  else if (slug.startsWith("docs/")) slug = slug.slice("docs/".length);

  // Check the default locale and every configured locale — a suppressed JA
  // page behind a surviving JA header link is just as much a 404.
  const targets = [{ locale: "(default)", dir: docsDir }, ...locales];
  // Tracked for the DEFAULT locale only. Collapsing every locale into one
  // "resolved anywhere" flag let a page that exists solely in a translation
  // suppress the warning for the default locale — which is the route that
  // actually 404s. A missing translation is normal and must stay silent; a
  // missing default-locale target is exactly what we cannot verify and must
  // say so. Cuts against this file's own "absence of findings is not evidence
  // of correctness" rule otherwise.
  let defaultResolved = false;

  for (const t of targets) {
    let resolved = null;
    for (const c of candidatesFor(t.dir, slug)) {
      if (await exists(c)) {
        resolved = c;
        break;
      }
    }
    if (!resolved) continue;
    if (t.locale === "(default)") defaultResolved = true;

    if (hasNoPage(frontmatter(await readFile(resolved, "utf-8")))) {
      failures.push(
        `[NAV-404] headerNav "${navPath}" targets ${relative(ROOT, resolved)} ` +
          `(locale ${t.locale}), which sets category_no_page. That page is ` +
          `never emitted, so the header link 404s. Remove the nav entry or ` +
          `drop category_no_page.`,
      );
    }
  }

  if (!defaultResolved) unresolved.push({ navPath, dir: targetDirFor(docsDir, slug) });
}

if (unresolved.length > 0) {
  const probed = [...new Set(unresolved.map((u) => u.dir).filter(Boolean))];
  const { ran, reason, accepted: generated } = await probeGeneratedDirs(probed);
  let exempted = 0;

  for (const u of unresolved) {
    const rule = u.dir ? generated.get(u.dir) : undefined;
    if (rule) {
      exempted++;
      // On the notes/stdout channel on purpose: a deliberate exemption stays
      // visible and auditable (rule file + line), and can never masquerade as
      // "found nothing to check".
      notes.push(
        `[GENERATED] headerNav "${u.navPath}" — target dir is gitignored by ` +
          `${rule} (build-generated); resolution deferred to the build.`,
      );
      continue;
    }
    warnings.push(
      `[UNRESOLVED] headerNav "${u.navPath}" — no source file found in the ` +
        `default content dir (${docsDir}). Verify this link manually; the ` +
        `check could not.`,
    );
  }

  if (ran) {
    notes.push(
      `probed ${probed.length} unique target dir(s) for ${unresolved.length} ` +
        `unresolved nav entr(ies) against in-repo .gitignore rules; ` +
        `${exempted} exempted as build-generated`,
    );
  } else {
    // Never phrase a skipped probe as a completed one: "0 exempted" would read
    // as "git says none of these are generated" when git was never asked.
    warnings.push(
      `[PROBE-SKIPPED] did NOT probe ${probed.length} unique target dir(s) for ` +
        `${unresolved.length} unresolved nav entr(ies) — ${reason}. Every ` +
        `unresolved entry above is kept as a warning; none was cleared.`,
    );
  }
}

// ── Report ────────────────────────────────────────────────────────────────
// Counts always print, so "checked nothing" can never masquerade as "all good".
for (const n of notes) console.log(`  · ${n}`);
for (const w of warnings) console.warn(`  ⚠️  ${w}`);

if (failures.length === 0) {
  console.log(`OK — category metadata check passed (${sidecars.length} sidecar(s) found).`);
  process.exit(0);
}

console.error("");
console.error(`FAILED — ${failures.length} category metadata problem(s):`);
for (const f of failures) console.error(`   - ${f}`);
process.exit(1);
